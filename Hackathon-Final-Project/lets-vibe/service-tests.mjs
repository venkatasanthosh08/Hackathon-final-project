const mem = {}; const sess = {};
globalThis.localStorage = { getItem:k=>k in mem?mem[k]:null, setItem:(k,v)=>{mem[k]=String(v)}, removeItem:k=>{delete mem[k]} };
globalThis.sessionStorage = { getItem:k=>k in sess?sess[k]:null, setItem:(k,v)=>{sess[k]=String(v)} };
const S = new URL("./src/services/", import.meta.url).href;
const plans = await import(S+"plans.js"), rooms = await import(S+"rooms.js"), streams = await import(S+"streams.js"), creator = await import(S+"creator.js"), an = await import(S+"analytics.js");
let pass=0, fail=0; const t=(n,c)=>{ c?pass++:fail++; console.log((c?"PASS ":"FAIL ")+n); };
const U=(n)=>({email:n+"@x.com",name:n});
const host=U("host"), g1=U("g1"), g2=U("g2"), g3=U("g3"), g4=U("g4");
t("default plan basic", plans.getPlanId(host.email)==="basic");
t("basic cannot create room", !!rooms.createRoom(host).error);
plans.selectPlan(host.email,"premium");
const r = rooms.createRoom(host); t("premium creates room", !!r.room && r.room.code.length===6);
const code=r.room.code;
t("create again returns existing", rooms.createRoom(host).existing===true);
t("invalid code error", /not found/i.test(rooms.joinRoom("ZZZZZZ",g1).error));
t("guest joins", !!rooms.joinRoom(code,g1).room);
t("same account rejoin not double counted", rooms.joinRoom(code,g1).room.participants.length===2);
rooms.joinRoom(code,g2); rooms.joinRoom(code,g3);
t("room at 4/4", rooms.getRoom(code).participants.length===4 && rooms.roomSeats(rooms.getRoom(code))==="4/4");
t("5th person sees full message", rooms.joinRoom(code,g4).error==="Sorry! This Vibe Together room is full.");
t("guest cannot control playback", !!rooms.setPlayback(code,g1.email,{playing:true,time:5}).error);
t("host can control playback", rooms.setPlayback(code,host.email,{playing:true,time:5}).room.playback.playing===true);
t("guest cannot change video", !!rooms.setRoomVideo(code,g1.email,3).error);
t("host changes video", rooms.setRoomVideo(code,host.email,3).room.movieId===3);
rooms.leaveRoom(code,g1.email);
t("seat freed after guest leaves", !!rooms.joinRoom(code,g4).room);
rooms.leaveRoom(code,host.email);
t("host leaving closes room", rooms.getRoom(code).status==="closed");
t("cannot join closed room", /closed/i.test(rooms.joinRoom(code,g1).error));
// premium expiry
plans.selectPlan(host.email,"premium"); const r2=rooms.createRoom(host); plans.expirePlanNow(host.email);
t("expired premium ends room", rooms.getRoom(r2.room.code).status==="closed" && /Premium/.test(rooms.getRoom(r2.room.code).closedReason));
t("expired host falls back to basic", plans.getPlanId(host.email)==="basic");
// device limits
plans.selectPlan(g1.email,"basic");
t("claim stream ok", streams.claimStream(g1.email,1).ok);
sess.deviceId="dev_B"; t("2nd device ok (basic=2)", streams.claimStream(g1.email,1).ok);
sess.deviceId="dev_C"; t("3rd device blocked on basic", !streams.claimStream(g1.email,1).ok);
plans.selectPlan(g1.email,"standard"); t("3rd device ok on standard", streams.claimStream(g1.email,1).ok);
// creator
const sub=creator.submitVideo(g1,{title:"T",description:"D",category:"Short Film",thumbnailUrl:"https://a.b/c.jpg",videoUrl:"https://a.b/v.mp4"});
t("submission pending", sub.item.status==="Pending");
t("bad url rejected", !!creator.submitVideo(g1,{title:"T",description:"D",category:"Short Film",thumbnailUrl:"x",videoUrl:"y"}).error);
t("pending not public", !creator.getApproved().some(s=>s.id===sub.item.id));
t("non-admin cannot review", !!creator.reviewSubmission(sub.item.id,"Approved"));
sess.loggedInRole="admin";
t("admin approves", creator.reviewSubmission(sub.item.id,"Approved")===null && creator.getApproved().some(s=>s.id===sub.item.id));
t("admin rejects -> hidden", (creator.reviewSubmission(sub.item.id,"Rejected"),!creator.getApproved().some(s=>s.id===sub.item.id)));
streams.logWatch({contentId:1,genre:"Sci-Fi"});
const a=an.getAnalytics(); t("analytics for admin", a && a.totals.roomsCreated===2 && a.totals.watchSessions===1 && a.moods===null);
t("analytics has no emails/passwords", !/@x\.com|password/i.test(JSON.stringify(a)));
sess.loggedInRole="user"; t("analytics null for non-admin", an.getAnalytics()===null);
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail?1:0);
